export function createDefaultTagGroups(): TagGroup[] {
  const legacyNames: Record<string, string> = {
    'standard-model': '通用标准模特',
    'garment-fidelity': '通用服饰保真',
    'bag-scene': '通用包包场景',
    'dance-socks': '通用舞蹈袜',
    'dance-shoes': '通用舞蹈鞋',
    'dance-pants': '黑色七分舞蹈裤',
  };
  const createSubcategory = (seed: SubcategorySeed) => ({
    id: seed.id,
    name: seed.name,
    dimensions: (DOCUMENT_DIMENSION_LAYOUTS[seed.id] ?? Object.keys(seed.dimensions).map((name) => [name, [name]] as [string, string[]])).map(([name, sources], dimensionIndex) => ({
      id: `${seed.id}-dimension-${dimensionIndex + 1}`,
      name,
      tags: sources.flatMap((source) => seed.dimensions[source] ?? []).map(([tagName, prompt], tagIndex) => ({
        id: `${seed.id}-${dimensionIndex + 1}-${tagIndex + 1}`,
        name: tagName,
        prompt,
      })),
    })),
  });
  return GROUPS.map((group) => ({
    id: group.id,
    name: group.name,
    promptTemplate: GROUP_PROMPT_TEMPLATES[group.id] ?? '',
    subcategories: [
      ...(DOCUMENT_SUBCATEGORIES[group.id] ?? []).map((seed) => createSubcategory(seed)),
      ...(group.id === 'standard-model' ? [] : [createSubcategory({ id: `${group.id}-general`, name: legacyNames[group.id] ?? '通用', dimensions: group.dimensions })]),
    ],
  }));
}
