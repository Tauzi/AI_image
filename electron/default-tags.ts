function createDimensions(prefix: string, modelPrompt: string): TagCategory[] {
  return DIMENSIONS.map(([name, tags], dimensionIndex) => ({
    id: `${prefix}-dimension-${dimensionIndex + 1}`,
    name,
    tags: tags.map(([tagName, prompt], tagIndex) => ({
      id: `${prefix}-${dimensionIndex + 1}-${tagIndex + 1}`,
      name: tagName,
      prompt: name === '图片类型' && tagName !== '模特换衣' ? `${modelPrompt}。${prompt}` : prompt,
    })),
  }));
}

